export interface CareRecord {
  id: string;
  ownerId: string;
  petId: string;
  parent: Row;
  subtype: Row;
}

/** Inserts a CARE_RECORDS parent and its matching subtype row, as one logical write. */
export async function createCareRecord(
  db: Db,
  kind: Kind,
  ownerId: unknown,
  petId: unknown,
  subtypeOverrides: Row = {},
  parentOverrides: Row = {},
): Promise<CareRecord> {
  const parent = await insert(db, 'care_records', {
    owner_id: ownerId,
    pet_id: petId,
    kind,
    occurrence_date: '2026-10-01',
    ...parentOverrides,
  });
  const subtype = await insert(db, SUBTYPE_TABLE[kind], {
    record_id: parent.id,
    owner_id: ownerId,
    pet_id: petId,
    ...SUBTYPE_DEFAULTS[kind],
    ...subtypeOverrides,
  });
  return {
    id: parent.id as string,
    ownerId: ownerId as string,
    petId: petId as string,
    parent,
    subtype,
  };
}

