/**
 * Creates a stock batch together with the ledger transaction and entry that justify its balance,
 * which is what the application does for OPENING and RESTOCK.
 */
export async function createStockedBatch(
  db: Db,
  item: Row,
  quantity: string,
  overrides: Row = {},
  type: 'OPENING' | 'RESTOCK' = 'OPENING',
): Promise<{ batch: Row; transaction: Row; entry: Row }> {
  const batch = await insert(db, 'stock_batches', {
    owner_id: item.owner_id,
    item_id: item.id,
    remaining_quantity: quantity,
    ...overrides,
  });
  const transaction = await insert(db, 'stock_transactions', {
    owner_id: item.owner_id,
    item_id: item.id,
    type,
    request_key: unique('req'),
  });
  const entry = await insert(db, 'stock_entries', {
    owner_id: item.owner_id,
    item_id: item.id,
    transaction_id: transaction.id,
    transaction_type: type,
    batch_id: batch.id,
    signed_quantity: quantity,
  });
  return { batch, transaction, entry };
}
