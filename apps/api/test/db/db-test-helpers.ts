/**
 * Helpers for the database-constraint e2e specs. They talk to PostgreSQL directly (no Prisma)
 * so each test exercises the migrated schema itself: CHECKs, composite same-owner FKs, partial
 * unique indexes and triggers. Every test runs inside a transaction that is always rolled back.
 */
import 'dotenv/config';
import { randomUUID } from 'node:crypto';
import pg from 'pg';

export type Db = pg.PoolClient;
export type Row = Record<string, unknown>;

/** PostgreSQL SQLSTATE codes the specs assert on. */
export const PgError = {
  FOREIGN_KEY: '23503',
  UNIQUE: '23505',
  CHECK: '23514',
  NOT_NULL: '23502',
  RAISED: 'P0001',
} as const;

function databaseUrl(): string {
  const url = process.env.DATABASE_URL;
  if (!url) throw new Error('DATABASE_URL must be set to run the database e2e specs');
  return url;
}

const pool = new pg.Pool({ connectionString: databaseUrl(), max: 4 });

export async function closePool(): Promise<void> {
  await pool.end();
}

/** Runs `fn` in a transaction that is always rolled back, so specs never leave data behind. */
export async function inRolledBackTx(fn: (db: Db) => Promise<void>): Promise<void> {
  const db = await pool.connect();
  try {
    await db.query('BEGIN');
    await fn(db);
  } finally {
    await db.query('ROLLBACK');
    db.release();
  }
}

export interface ExpectedViolation {
  code: string;
  /** Exact constraint name, or a pattern when the name is generated by Prisma. */
  constraint?: string | RegExp;
  message?: RegExp;
}

/**
 * Runs `action` inside a savepoint and asserts it fails with the expected error. Deferred
 * constraints are forced to run immediately, so commit-time checks are asserted too. The
 * savepoint is rolled back afterwards, so the surrounding transaction stays usable.
 */
export async function expectViolation(
  db: Db,
  action: () => Promise<unknown>,
  expected: ExpectedViolation,
): Promise<void> {
  await db.query('SAVEPOINT expect_violation');
  let error: (Error & { code?: string; constraint?: string }) | undefined;
  try {
    await action();
    await db.query('SET CONSTRAINTS ALL IMMEDIATE');
  } catch (e) {
    error = e as typeof error;
  }
  await db.query('ROLLBACK TO SAVEPOINT expect_violation');
  await db.query('SET CONSTRAINTS ALL DEFERRED');

  expect(error, 'expected the statement to be rejected').toBeDefined();
  expect({ code: error?.code, message: error?.message }).toMatchObject({ code: expected.code });
  if (expected.constraint !== undefined) {
    if (typeof expected.constraint === 'string') {
      expect(error?.constraint).toBe(expected.constraint);
    } else {
      expect(error?.constraint).toMatch(expected.constraint);
    }
  }
  if (expected.message) expect(error?.message).toMatch(expected.message);
}

/** Forces deferred (commit-time) constraints to run now; throws if any fail. */
export async function checkDeferred(db: Db): Promise<void> {
  await db.query('SET CONSTRAINTS ALL IMMEDIATE');
  await db.query('SET CONSTRAINTS ALL DEFERRED');
}

/** INSERT a row and return it. Column names are trusted test constants, values are bound. */
export async function insert(db: Db, table: string, row: Row): Promise<Row> {
  const columns = Object.keys(row);
  const placeholders = columns.map((_, i) => `$${i + 1}`);
  const { rows } = await db.query<Row>(
    `INSERT INTO ${table} (${columns.join(', ')}) VALUES (${placeholders.join(', ')}) RETURNING *`,
    Object.values(row),
  );
  return rows[0];
}

export function unique(prefix: string): string {
  return `${prefix}-${randomUUID()}`;
}

