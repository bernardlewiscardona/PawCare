function amoxicillinLogs(): DoseLog[] {
  const logs: DoseLog[] = [];
  for (const day of ['05', '06', '07', '08', '09']) {
    for (const time of ['08:00', '20:00']) {
      const skipped = day === '09' && time === '20:00';
      logs.push({
        id: `dose-amox-${day}-${time}`,
        prescriptionId: 'rx-amox',
        date: `2026-11-${day}`,
        time,
        status: skipped ? 'skipped' : 'taken',
        at: skipped ? undefined : time === '08:00' ? '08:06' : '20:04',
        note: skipped ? 'vomited after dinner' : undefined,
      });
    }
  }
  logs.push({
    id: 'dose-amox-10-08:00',
    prescriptionId: 'rx-amox',
    date: '2026-11-10',
    time: '08:00',
    status: 'taken',
    at: '08:04',
  });
  return logs;
}

